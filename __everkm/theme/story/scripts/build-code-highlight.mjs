#!/usr/bin/env node
/**
 * Merge two syntect theme CSS files into code-highlight.css with light/dark scopes.
 *
 * Usage:
 *   node scripts/build-code-highlight.mjs <light.css> <dark.css> [output.css]
 *
 * Examples:
 *   pnpm run code-highlight:build base16-ocean.light.css base16-ocean.dark.css
 *   node scripts/build-code-highlight.mjs code_themes/base16-ocean.light.css code_themes/base16-ocean.dark.css
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const THEMES_DIR = path.join(ROOT, "src/assets/css/code_themes");
const DEFAULT_OUT = path.join(ROOT, "src/assets/css/code-highlight.css");
const SCOPE = ".app-prose pre:not(.astro-code)";

function usage() {
  console.error(`Usage: node scripts/build-code-highlight.mjs <light.css> <dark.css> [output.css]

  light.css / dark.css  Filename under src/assets/css/code_themes/, or any path.
  output.css            Default: src/assets/css/code-highlight.css`);
  process.exit(1);
}

function resolveThemeFile(arg) {
  if (!arg) return null;
  const candidates = [
    path.resolve(process.cwd(), arg),
    path.join(THEMES_DIR, arg),
    path.join(ROOT, arg),
  ];
  for (const p of candidates) {
    if (fs.existsSync(p)) return p;
  }
  return null;
}

function prefixSelector(selector) {
  return selector
    .split(",")
    .map((s) => `${SCOPE} ${s.trim()}`)
    .join(", ");
}

function transformSyntectCss(css) {
  const lines = css.split("\n");
  const out = [];
  let i = 0;

  while (i < lines.length) {
    const trimmed = lines[i].trim();
    if (!trimmed || trimmed.startsWith("/*") || trimmed.startsWith("*")) {
      i++;
      continue;
    }

    const selMatch = trimmed.match(/^([^{]+)\{/);
    if (!selMatch) {
      i++;
      continue;
    }

    const selector = selMatch[1].trim();
    const props = [];
    i++;
    while (i < lines.length && !lines[i].trim().startsWith("}")) {
      props.push(lines[i]);
      i++;
    }

    if (selector === ".code") {
      const bg = props.find((p) => p.includes("background-color"));
      const color = props.find(
        (p) => p.includes("color:") && !p.includes("background-color")
      );
      const other = props.filter((p) => p !== bg && p !== color);
      if (bg) out.push(`${SCOPE} {${bg}}`);
      if (color) out.push(`${SCOPE} > code {${color}}`);
      for (const p of other) out.push(`${SCOPE} > code {${p}}`);
    } else {
      out.push(`${prefixSelector(selector)} {`);
      for (const p of props) out.push(p);
      out.push("}");
    }
    i++;
  }

  return out.join("\n");
}

function themeLabel(filePath) {
  const base = path.basename(filePath, path.extname(filePath));
  return base.replace(/[.-]/g, " ");
}

function wrapBlock(css, themeAttr) {
  const indented = css
    .split("\n")
    .map((line) => (line ? `  ${line}` : line))
    .join("\n");
  return `${themeAttr} {\n${indented}\n}`;
}

function buildCodeHighlight(lightPath, darkPath) {
  const lightCss = transformSyntectCss(fs.readFileSync(lightPath, "utf8"));
  const darkCss = transformSyntectCss(fs.readFileSync(darkPath, "utf8"));

  return `/* Server-side syntect code highlighting (everkm-publish code_highlight.server) */
/* Light: ${path.basename(lightPath)} | Dark: ${path.basename(darkPath)} */
/* Scoped under ${SCOPE} — generated by scripts/build-code-highlight.mjs */

@layer components {
${wrapBlock(lightCss, ":root,\n[data-theme=\"light\"]")}
\n${wrapBlock(darkCss, "[data-theme=\"dark\"]")}
}
`;
}

const [lightArg, darkArg, outArg] = process.argv.slice(2);
if (!lightArg || !darkArg) usage();

const lightPath = resolveThemeFile(lightArg);
const darkPath = resolveThemeFile(darkArg);
if (!lightPath) {
  console.error(`Light theme not found: ${lightArg}`);
  process.exit(1);
}
if (!darkPath) {
  console.error(`Dark theme not found: ${darkArg}`);
  process.exit(1);
}

const outPath = outArg
  ? path.resolve(process.cwd(), outArg)
  : DEFAULT_OUT;

const result = buildCodeHighlight(lightPath, darkPath);
fs.writeFileSync(outPath, result);

console.log(`Generated ${path.relative(ROOT, outPath)}`);
console.log(`  light: ${path.relative(ROOT, lightPath)} (${themeLabel(lightPath)})`);
console.log(`  dark:  ${path.relative(ROOT, darkPath)} (${themeLabel(darkPath)})`);
